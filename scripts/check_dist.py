"""Gate what the interlock distributions may contain, before CI passes them or anyone uploads.

The sdist is built from a working tree, and a working tree can hold files that must never be
published. The build is told what to include (pyproject `only-include`); this gate checks the
archives it actually produced against the same allow-list. It never lists what to keep out:
anything not named here fails. An allowed root is not enough on its own: every member must also
be a file git tracks (the build's PKG-INFO and wheel metadata aside), so a file the tree hides
only through an ignore or exclude list cannot ship from under a root, and a dotfile, a
__pycache__ dir or bytecode fails by its shape even when tracked.

Usage: python scripts/check_dist.py [DIST_DIR]   (default: dist; run inside the git checkout)
Exit 0 and "check_dist: ok" when both archives pass, 1 with every offending path otherwise.
"""

from __future__ import annotations

import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

# Mirrors [tool.hatch.build.targets.sdist] only-include in pyproject.toml, plus the two files
# hatchling adds on its own: the generated PKG-INFO and the .gitignore it read.
ALLOWED_SDIST_ROOTS = frozenset(
    {
        "src/interlock",
        "tests",
        "lab",
        "docs",
        "Dockerfile",
        "Dockerfile.vuln",
        "lab.sh",
        "docker-compose.yml",
        "docker-compose.tap.yml",
        "docker-compose.fuzz.yml",
        "docker-compose.downgrade.yml",
        "docker-compose.spoof.yml",
        "docker-compose.replay.yml",
        "docker-compose.cve.yml",
        "docker-compose.vuln.yml",
        "docker-compose.lockstate.yml",
        "README.md",
        "LICENSE",
        "NOTICE",
        "pyproject.toml",
        "PKG-INFO",
        ".gitignore",
    }
)

# Excluded from the docs root: recordings for the repository page, not for the archive.
EXCLUDED_SDIST_PREFIXES = ("docs/media/",)

LICENCE_FILES = ("LICENSE", "NOTICE")

# The checkout the archives are built from; its git index is what a member must be part of.
REPO_ROOT = Path(__file__).resolve().parent.parent

# Generated by the build rather than copied from the tree, so absent from the git index.
GENERATED_SDIST_MEMBERS = frozenset({"PKG-INFO"})

# The one dotfile an archive may carry: hatchling adds the root .gitignore it read.
ALLOWED_DOTFILES = frozenset({".gitignore"})

# Never published at any depth, tracked or not: interpreter caches and bytecode.
DENIED_PARTS = frozenset({"__pycache__"})
DENIED_SUFFIXES = (".pyc", ".pyo")


def _single(dist: Path, pattern: str, kind: str, problems: list[str]) -> Path | None:
    found = sorted(dist.glob(pattern))
    if len(found) != 1:
        names = ", ".join(p.name for p in found) or "none"
        problems.append(f"expected exactly one {kind} ({pattern}) in {dist}, found: {names}")
        return None
    return found[0]


def tracked_files(repo: Path) -> frozenset[str] | None:
    """Return every path git tracks in ``repo``, or None when git cannot list them."""
    try:
        result = subprocess.run(
            ["git", "-C", str(repo), "ls-files", "-z"], capture_output=True, check=False
        )
    except OSError:
        return None
    if result.returncode != 0:
        return None
    listed = result.stdout.decode("utf-8", "surrogateescape").split("\0")
    return frozenset(path for path in listed if path)


def _denied(rel: str) -> bool:
    """Return True for a dotfile or dot dir (the root .gitignore aside), __pycache__ or bytecode."""
    if rel in ALLOWED_DOTFILES:
        return False
    parts = rel.split("/")
    return (
        any(part.startswith(".") or part in DENIED_PARTS for part in parts)
        or rel.endswith(DENIED_SUFFIXES)
    )


def _allowed_in_sdist(rel: str, is_dir: bool) -> bool:
    if rel.startswith(EXCLUDED_SDIST_PREFIXES) or rel + "/" in EXCLUDED_SDIST_PREFIXES:
        return False
    for root in ALLOWED_SDIST_ROOTS:
        if rel == root or rel.startswith(root + "/"):
            return True
        if is_dir and root.startswith(rel + "/"):
            return True
    return False


def check_sdist(sdist: Path, tracked: frozenset[str]) -> list[str]:
    """Return every sdist member outside the allow-list, denied or untracked, and missing licences.

    ``tracked`` is the git index of the checkout the sdist was built from.
    """
    prefix = sdist.name.removesuffix(".tar.gz") + "/"
    problems: list[str] = []
    present: set[str] = set()
    with tarfile.open(sdist, "r:gz") as archive:
        for member in archive.getmembers():
            name = member.name
            if name == prefix.rstrip("/"):
                continue
            if not name.startswith(prefix):
                problems.append(f"sdist path outside {prefix}: {name}")
                continue
            rel = name.removeprefix(prefix).rstrip("/")
            present.add(rel)
            if not _allowed_in_sdist(rel, member.isdir()):
                problems.append(f"sdist path not allowed: {rel}")
            elif _denied(rel):
                problems.append(f"sdist path denied: {rel}")
            elif not member.isdir() and rel not in tracked and rel not in GENERATED_SDIST_MEMBERS:
                problems.append(f"sdist path not tracked by git: {rel}")
    problems.extend(
        f"sdist lacks {name} at its root" for name in LICENCE_FILES if name not in present
    )
    return problems


def check_wheel(wheel: Path, tracked: frozenset[str]) -> list[str]:
    """Return every wheel member outside the package and its dist-info, denied or untracked.

    Package members come from ``src/`` (``packages = ["src/interlock"]``), so each must be in
    ``tracked`` under that prefix; the dist-info is generated. Missing licences are reported.
    """
    name, version = wheel.name.split("-")[:2]
    package = f"{name}/"
    dist_info = f"{name}-{version}.dist-info/"
    allowed = (package, dist_info)
    with zipfile.ZipFile(wheel) as archive:
        members = archive.namelist()
    problems: list[str] = []
    for member in members:
        if not member.startswith(allowed):
            problems.append(f"wheel path not allowed: {member}")
        elif _denied(member.rstrip("/")):
            problems.append(f"wheel path denied: {member}")
        elif member.startswith(package) and not member.endswith("/") and (
            f"src/{member}" not in tracked
        ):
            problems.append(f"wheel path not tracked by git: {member}")
    problems.extend(
        f"wheel lacks {dist_info}licenses/{licence}"
        for licence in LICENCE_FILES
        if f"{dist_info}licenses/{licence}" not in members
    )
    return problems


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    dist = Path(args[0] if args else "dist")
    if not dist.is_dir():
        print(f"check_dist: {dist} is not a directory", file=sys.stderr)
        return 1
    problems: list[str] = []
    sdist = _single(dist, "interlock-*.tar.gz", "sdist", problems)
    wheel = _single(dist, "interlock-*.whl", "wheel", problems)
    tracked = tracked_files(REPO_ROOT)
    if tracked is None:
        problems.append(
            f"cannot list the tracked files of {REPO_ROOT} (git ls-files failed), "
            "so no member is checked"
        )
    else:
        if sdist is not None:
            problems.extend(check_sdist(sdist, tracked))
        if wheel is not None:
            problems.extend(check_wheel(wheel, tracked))
    if problems:
        for problem in problems:
            print(f"check_dist: {problem}", file=sys.stderr)
        return 1
    print("check_dist: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
